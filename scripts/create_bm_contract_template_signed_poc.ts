function buildRequisitesTable(sigBuf: Buffer, stampBuf: Buffer): Table {
  // ─ Левая колонка: Исполнитель ─────────────────────────────────────────────

  const execTitleCell = cell([
    p('Исполнитель', { bold: true, align: AlignmentType.CENTER, spaceAfter: 40 }),
    p('ООО «Золото Арктики»', { bold: true, align: AlignmentType.CENTER, spaceAfter: 0 }),
  ], 50);

  const execReqCell = cell(
    EXEC_FIXED_REQUISITES.map(line => p(line, { size: FONT_SIZE_SMALL, spaceAfter: 20 })),
    50,
  );

  // Ячейка подписи исполнителя — содержит СТАТИЧЕСКИЕ изображения.
  // docxtemplater не трогает <a:blip r:embed="..."/> — только <w:t> текст-ноды.
  const execSigCell = cell([
    // Подпись (110×45 pt)
    new Paragraph({
      spacing: { after: 0 },
      children: [
        new ImageRun({
          data: sigBuf,
          transformation: { width: 110, height: 45 },
          type: 'png',
        } as any),
      ],
    }),
    // Печать (110×110 pt)
    new Paragraph({
      spacing: { after: 60 },
      children: [
        new ImageRun({
          data: stampBuf,
          transformation: { width: 110, height: 110 },
          type: 'png',
        } as any),
      ],
    }),
    p('_______________________   /Е. А. Сташ/', { size: FONT_SIZE_SMALL, spaceAfter: 0 }),
    p('Генеральный директор', { size: FONT_SIZE_SMALL }),
  ], 50);

  // ─ Правая колонка: Гость ──────────────────────────────────────────────────

  const clientTitleCell = cell([
    p('Гость', { bold: true, align: AlignmentType.CENTER, spaceAfter: 40 }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 0 },
      children: [new TextRun({ text: '{client_name}', bold: true, font: FONT, size: FONT_SIZE })],
    }),
  ], 50);

  const clientFields: Array<[string, string]> = [
    ['Ф.И.О.', '{client_name}'],
    ['Дата рождения', '{client_dob}'],
    ['Тип документа', '{client_passport_type}'],
    ['Серия и номер', '{client_passport}'],
    ['Дата выдачи', '{client_passport_date}'],
    ['Кем выдан', '{client_passport_by}'],
    ['Код подразделения', '{client_passport_code}'],
    ['Адрес регистрации', '{client_address}'],
    ['Телефон', '{client_phone}'],
    ['E-mail', '{client_email}'],
  ];

  const clientReqCell = cell(
    clientFields.map(([label, tagStr]) =>
      new Paragraph({
        spacing: { after: 20 },
        children: [
          new TextRun({ text: `${label}: `, font: FONT, size: FONT_SIZE_SMALL }),
          new TextRun({ text: tagStr, bold: true, font: FONT, size: FONT_SIZE_SMALL }),
        ],
      }),
    ),
    50,
  );

  const clientSigCell = cell([
    // Зарезервированное место под высоту подписи + печати Исполнителя,
    // чтобы строки подписей были на одном уровне.
    p('', { spaceAfter: 200 }),
    new Paragraph({
      spacing: { after: 0 },
      children: [
        new TextRun({ text: '_______________________   /', font: FONT, size: FONT_SIZE_SMALL }),
        new TextRun({ text: '{client_short_name}', font: FONT, size: FONT_SIZE_SMALL }),
        new TextRun({ text: '/', font: FONT, size: FONT_SIZE_SMALL }),
      ],
    }),
    p('Гость', { size: FONT_SIZE_SMALL }),
  ], 50);

  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: NO_BORDER as any,
    rows: [
      new TableRow({ cantSplit: true, children: [execTitleCell, clientTitleCell] }),
      new TableRow({ children: [execReqCell, clientReqCell] }),
      new TableRow({ cantSplit: true, children: [execSigCell, clientSigCell] }),
    ],
  });
}

