// ---------------------------------------------------------------------------
// Хелперы
// ---------------------------------------------------------------------------

function p(
  text: string,
  opts: {
    bold?: boolean;
    align?: DocxAlignment;
    size?: number;
    spaceAfter?: number;
    pageBreakBefore?: boolean;
    keepNext?: boolean;
  } = {},
): Paragraph {
  return new Paragraph({
    alignment: opts.align,
    spacing: { after: opts.spaceAfter ?? SPACE_AFTER },
    pageBreakBefore: opts.pageBreakBefore,
    keepNext: opts.keepNext,
    children: [
      new TextRun({
        text,
        bold: opts.bold,
        font: FONT,
        size: opts.size ?? FONT_SIZE,
      }),
    ],
  });
}

function h(text: string, opts: { pageBreakBefore?: boolean } = {}): Paragraph {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 200, after: 120 },
    keepNext: true,
    pageBreakBefore: opts.pageBreakBefore,
    children: [new TextRun({ text, bold: true, font: FONT, size: FONT_SIZE })],
  });
}

function mixed(
  parts: Array<{ text: string; bold?: boolean }>,
  opts: { align?: DocxAlignment; spaceAfter?: number } = {},
): Paragraph {
  return new Paragraph({
    alignment: opts.align,
    spacing: { after: opts.spaceAfter ?? SPACE_AFTER },
    children: parts.map(({ text, bold }) =>
      new TextRun({ text, bold: bold ?? false, font: FONT, size: FONT_SIZE }),
    ),
  });
}

function tag(name: string, bold = true): { text: string; bold?: boolean } {
  return { text: `{${name}}`, bold };
}

function txt(s: string): { text: string } {
  return { text: s };
}

function cell(children: (Paragraph | Table)[], width: number): TableCell {
  return new TableCell({
    width: { size: width, type: WidthType.PERCENTAGE },
    margins: { top: 80, bottom: 80, left: 120, right: 120 },
    borders: NO_BORDER as any,
    children,
  });
}

