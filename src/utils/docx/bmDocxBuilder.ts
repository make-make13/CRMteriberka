function p(text: string, opts: { bold?: boolean; align?: AlignmentType; size?: number; spaceAfter?: number; pageBreakBefore?: boolean; keepNext?: boolean } = {}): Paragraph {
  return new Paragraph({
    alignment: opts.align,
    spacing: { after: opts.spaceAfter ?? SPACE_AFTER },
    pageBreakBefore: opts.pageBreakBefore,
    keepNext: opts.keepNext,
    children: [
      new TextRun({
        text: normalizeRu(text),
        bold: opts.bold,
        font: FONT,
        size: opts.size ?? FONT_SIZE,
      }),
    ],
  });
}

function h(text: string, opts: { pageBreakBefore?: boolean } = {}): Paragraph {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 200, after: 120 },
    keepNext: true, // не отрывать заголовок от первого абзаца раздела
    pageBreakBefore: opts.pageBreakBefore,
    children: [new TextRun({ text: normalizeRu(text), bold: true, font: FONT, size: FONT_SIZE })],
  });
}

/** Параграф с подстановкой {var} → значение, переменные выделяются жирным. */
function mvt(template: string, vars: BmDocxVariables, opts: { align?: AlignmentType; size?: number } = {}): Paragraph {
  const parts = normalizeRu(template).split(/(\{[a-z_]+\})/gi);
  const children: TextRun[] = [];
  for (const part of parts) {
    const m = part.match(/^\{([a-z_]+)\}$/i);
    if (m) {
      const value = (vars as unknown as Record<string, string>)[m[1]] ?? '';
      children.push(new TextRun({ text: value, bold: true, font: FONT, size: opts.size ?? FONT_SIZE }));
    } else if (part.length > 0) {
      children.push(new TextRun({ text: part, font: FONT, size: opts.size ?? FONT_SIZE }));
    }
  }
  return new Paragraph({ alignment: opts.align, spacing: { after: SPACE_AFTER }, children });
}

/** Параграф для пункта со склейкой: набор кусков (текст или переменная). */
function multiLine(text: string, opts: { size?: number } = {}): Paragraph[] {
  // Разбиваем строку по \n и создаём отдельные параграфы
  return text.split('\n').map(line => p(line, { size: opts.size }));
}

