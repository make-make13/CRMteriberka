/**
 * Нормализация текста перед вставкой в DOCX:
 *  - "бутик-отел*" → non-breaking hyphen U+2011, чтобы слово не разрывалось при
 *    переносе строки (источник артефакта "бутик￾отеля" в PDF-text-extract);
 *  - унификация "ё" — там, где в исходных абзацах могло проскочить написание через "е".
 *
 * Внутри-builder'а это безопаснее, чем менять каждый литерал в исходнике.
 */
/**
 * "Фамилия Имя Отчество" → "И. О. Фамилия" — формат короткой подписи Гостя.
 *
 * Отличается от makeShortName в documentHelpers.ts тем, что между инициалами
 * добавляется пробел ("С. А. Федоров", а не "С.А. Федоров"). Используется
 * ТОЛЬКО в строке подписи в §15. В шапке таблицы и в реквизитах остаётся
 * полное ФИО (vars.client_name).
 */
function makeGuestShortName(fullName: string): string {
  const cleaned = String(fullName || '').trim().replace(/\s+/g, ' ');
  if (!cleaned) return '';
  const parts = cleaned.split(' ');
  if (parts.length === 1) return cleaned;
  const [last, first, middle] = parts;
  const initials = [first?.[0], middle?.[0]]
    .filter(Boolean)
    .map(l => `${l}.`)
    .join(' ');
  return initials ? `${initials} ${last}` : last;
}

function normalizeRu(input: string): string {
  let s = input;
  // NOTE: ранее здесь был replace бутик-отел → бутик‑отел (U+2011, non-breaking hyphen),
  // но LibreOffice при DOCX→PDF конвертации отображал U+2011 как ￾ (U+FFFE) в text-layer PDF.
  // Оставляем обычный ASCII дефис — Word/LibreOffice сам обработает перенос при необходимости.

  // Точечное исправление опечатки "лцами" → "лицами" — встречалась в §14.6.
  s = s.replace(/лцами/g, 'лицами');

  // Унификация "ё".
  // ВАЖНО: \b в JS не работает для кириллицы — приходится явно описывать
  // границу слова через lookaround по диапазону [а-яёА-ЯЁ].
  const NB = '(?<![а-яёА-ЯЁ])'; // not preceded by Russian letter
  const NA = '(?![а-яёА-ЯЁ])';  // not followed by Russian letter
  const yoMap: Array<[RegExp, string]> = [
    [new RegExp(NB + 'счете' + NA, 'g'), 'счёте'],
    [new RegExp(NB + 'счет' + NA, 'g'), 'счёт'],
    [new RegExp(NB + 'счета' + NA, 'g'), 'счёта'],
    [new RegExp(NB + 'счету' + NA, 'g'), 'счёту'],
    [new RegExp(NB + 'расчете' + NA, 'g'), 'расчёте'],
    [new RegExp(NB + 'расчета' + NA, 'g'), 'расчёта'],
    [new RegExp(NB + 'расчет' + NA, 'g'), 'расчёт'],
    [new RegExp(NB + 'расчетный' + NA, 'g'), 'расчётный'],
    [new RegExp(NB + 'расчетного' + NA, 'g'), 'расчётного'],
    [new RegExp(NB + 'расчетным' + NA, 'g'), 'расчётным'],
    [new RegExp(NB + 'перерасчета' + NA, 'g'), 'перерасчёта'],
    [new RegExp(NB + 'учетом' + NA, 'g'), 'учётом'],
    [new RegExp(NB + 'объему' + NA, 'g'), 'объёму'],
    [new RegExp(NB + 'несет' + NA, 'g'), 'несёт'],
    [new RegExp(NB + 'утвержденному' + NA, 'g'), 'утверждённому'],
    [new RegExp(NB + 'утвержденного' + NA, 'g'), 'утверждённого'],
    [new RegExp(NB + 'подтвержденные' + NA, 'g'), 'подтверждённые'],
    [new RegExp(NB + 'подтвержденных' + NA, 'g'), 'подтверждённых'],
    [new RegExp(NB + 'понесенные' + NA, 'g'), 'понесённые'],
    [new RegExp(NB + 'понесенных' + NA, 'g'), 'понесённых'],
    [new RegExp(NB + 'внесенная' + NA, 'g'), 'внесённая'],
    [new RegExp(NB + 'внесенной' + NA, 'g'), 'внесённой'],
    // учет-формы
    [new RegExp(NB + 'учета' + NA, 'g'), 'учёта'],
    [new RegExp(NB + 'учете' + NA, 'g'), 'учёте'],
    // расчет-формы (падежи, не покрытые выше)
    [new RegExp(NB + 'расчетов' + NA, 'g'), 'расчётов'],
  ];
  for (const [re, rep] of yoMap) s = s.replace(re, rep);
  return s;
}

